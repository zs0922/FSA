#!/usr/bin/env python3
"""Run the production HBM startup/gate RTL under two independently driven clocks.

This is digital protocol verification, not an analog metastability simulation or
a model of the HBM memory/PHY. Physical clocks and CDC are checked after routing.
"""
import argparse
import hashlib
import json
import re
from pathlib import Path
import shutil
import subprocess


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--rtl', type=Path, required=True)
    parser.add_argument('--out', type=Path, required=True)
    args = parser.parse_args()
    rtl, out = args.rtl.resolve(), args.out.resolve()
    out.mkdir(parents=True, exist_ok=True)
    for name in ('obj', 'results.json', 'simulation.log', 'verilator-build.log'):
        if (out / name).exists():
            raise SystemExit('Refusing to reuse verification output: ' + str(out / name))
    sources = sorted(rtl.glob('*.sv'))
    assert sources and (rtl / 'HBMStartupVerificationHarness.sv').is_file(), 'Missing emitted test RTL'
    assert (rtl / 'HBMAsyncLevelSynchronizer.sv').is_file(), 'Missing production inline synchronizer RTL'
    assert (rtl / 'HBMPLLResetControl.sv').is_file(), 'Missing production PLL reset controller RTL'
    versions = {version for path in sources for version in
                re.findall(r'^// Generated by CIRCT firtool-([0-9.]+)', path.read_text(), re.M)}
    assert versions == {'1.75.0'}, 'Unexpected RTL emitter version: ' + repr(versions)
    source = Path(__file__).with_name('hbm_startup_test.cpp').resolve()
    root = Path(__file__).resolve().parents[2]
    scala_inputs = [root / 'fpga/src/main/scala/u280/HBMStartup.scala',
                    root / 'fpga/src/test/scala/chipyard/fpga/u280/HBMStartupVerification.scala']
    verilator = shutil.which('verilator')
    assert verilator, 'verilator is required'
    version = subprocess.check_output([verilator, '--version'], text=True).strip()
    command = [verilator, '--cc', '--exe', '--build', '-j', '4', '-Wno-fatal',
               '--top-module', 'HBMStartupVerificationHarness', '--Mdir', str(out / 'obj'),
               '-CFLAGS', '-std=c++17', *map(str, sources), str(source)]
    with (out / 'verilator-build.log').open('w') as log:
        subprocess.run(command, stdout=log, stderr=subprocess.STDOUT, check=True)
    binary = out / 'obj/VHBMStartupVerificationHarness'
    with (out / 'simulation.log').open('w') as log:
        subprocess.run([str(binary)], stdout=log, stderr=subprocess.STDOUT, check=True)
    lines = (out / 'simulation.log').read_text().splitlines()
    results = json.loads(next(line for line in reversed(lines) if line.startswith('{')))
    assert results['passed'] and results['clock_scenarios'] == 8
    assert results['gate_vectors'] >= 32768 and results['checks'] > 100000
    assert results['short_complete_faults'] == 8 and results['partial_initialization_resets'] == 8
    assert results['pll_scenarios'] == 8 and results['pll_release_events'] == 32
    assert results['pll_stable_cycles'] == 7
    results.update({
        'scope': 'Production HBM startup control, five-channel AXI gate, and PLL/PERST reset qualification; digital CDC/reset protocol only',
        'metastability_or_hbm_phy_proven': False,
        'verilator': version,
        'rtl_firtool_versions': sorted(versions),
        'command': command,
        'inputs_sha256': {str(p): sha(p) for p in [*sources, *scala_inputs, source, Path(__file__).resolve()]},
        'binary_sha256': sha(binary),
        'simulation_log_sha256': sha(out / 'simulation.log'),
        'verilator_build_log_sha256': sha(out / 'verilator-build.log'),
    })
    (out / 'results.json').write_text(json.dumps(results, indent=2) + '\n')
    print('PASS: HBM independent-clock reset/startup and AXI gating verification')


if __name__ == '__main__':
    main()
